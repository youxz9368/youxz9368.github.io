  function renderTabView(tabsId, bodyId, groups) {
    var tabsEl = document.getElementById(tabsId);
    var bodyEl = document.getElementById(bodyId);
    tabsEl.innerHTML = groups.map(function (g, i) {
      return '<button class="tab-btn' + (i === 0 ? ' active' : '') + '" data-i="' + i + '">' + g.label + '</button>';
    }).join('');
    function show(i) {
      tabsEl.querySelectorAll('.tab-btn').forEach(function (b, bi) {
        b.classList.toggle('active', bi === i);
      });
      bodyEl.innerHTML = itemsHtml(groups[i].items);
      bodyEl.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    }
    tabsEl.querySelectorAll('.tab-btn').forEach(function (b) {
      b.addEventListener('click', function () { show(+b.dataset.i); });
    });
    show(0);
  }

